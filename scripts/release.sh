#!/usr/bin/env bash
# Publishes a release of NOTCH-ZAP-INATOR:
#
#   1. builds dist/NotchZapInator.app (scripts/bundle.sh)
#   2. packs it as dist/site/releases/NotchZapInator-<version>.tar.gz, next to
#      install.sh and `latest` ("<version> <sha256>")
#   3. deploys dist/site to zapinator.kunalbagaria.com (Cloudflare Worker in site/)
#   4. points the Homebrew cask in KunalBagaria/homebrew-zapinator at it
#
#   scripts/release.sh             all four (bump `version` in Cargo.toml first)
#   scripts/release.sh --dry-run   steps 1-2 and dist/zapinator.rb, nothing uploaded
#   scripts/release.sh --force     re-publish a version that's already live
set -euo pipefail

cd "$(dirname "$0")/.."

BASE_URL=https://zapinator.kunalbagaria.com
TAP_REPO=KunalBagaria/homebrew-zapinator
SITE=dist/site

dry_run=0 force=0
for arg in "$@"; do
    case $arg in
        --dry-run) dry_run=1 ;;
        --force) force=1 ;;
        *) echo "usage: $0 [--dry-run] [--force]" >&2; exit 2 ;;
    esac
done

VERSION=$(sed -n 's/^version = "\(.*\)"/\1/p' Cargo.toml | head -n1)

# A version's tarball must never change once it's out: Homebrew pins its
# checksum, and every rebuild has a different one.
if (( ! dry_run && ! force )); then
    live=$(curl -fsS "$BASE_URL/latest" 2>/dev/null | cut -d' ' -f1 || true)
    if [[ "$live" == "$VERSION" ]]; then
        echo "error: $VERSION is already live. Bump \`version\` in Cargo.toml (or pass --force)." >&2
        exit 1
    fi
fi

scripts/bundle.sh

echo "==> packing $VERSION"
rm -rf "$SITE"
mkdir -p "$SITE/releases"
TARBALL="$SITE/releases/NotchZapInator-$VERSION.tar.gz"
# No AppleDouble files or extended attributes: just the signed bundle.
COPYFILE_DISABLE=1 tar --no-mac-metadata --no-xattrs -czf "$TARBALL" -C dist NotchZapInator.app
SHA=$(shasum -a 256 "$TARBALL" | cut -d' ' -f1)
cp scripts/install.sh "$SITE/install.sh"
printf '%s %s\n' "$VERSION" "$SHA" > "$SITE/latest"
{
    echo "# Generated by scripts/release.sh from packaging/zapinator.rb in the main project."
    sed -e '1,2d' -e "s/__VERSION__/$VERSION/" -e "s/__SHA256__/$SHA/" packaging/zapinator.rb
} > dist/zapinator.rb
echo "    $TARBALL ($(du -h "$TARBALL" | cut -f1 | tr -d ' '), sha256 $SHA)"

if (( dry_run )); then
    echo "==> dry run: not deploying. Files are in $SITE and dist/zapinator.rb"
    exit 0
fi

echo "==> deploying $BASE_URL"
wrangler deploy --config site/wrangler.jsonc

echo "==> checking the live download"
live=$(curl -fsS "$BASE_URL/latest")
[[ "$live" == "$VERSION $SHA" ]] || { echo "error: $BASE_URL/latest says '$live'" >&2; exit 1; }
curl -fsS "$BASE_URL/releases/NotchZapInator-$VERSION.tar.gz" | shasum -a 256 | grep -q "^$SHA " ||
    { echo "error: the live tarball's checksum doesn't match" >&2; exit 1; }

echo "==> updating the Homebrew cask ($TAP_REPO)"
rm -rf dist/tap
gh repo clone "$TAP_REPO" dist/tap -- --quiet
mkdir -p dist/tap/Casks
cp dist/zapinator.rb dist/tap/Casks/zapinator.rb
git -C dist/tap add Casks/zapinator.rb
if git -C dist/tap diff --cached --quiet; then
    echo "    cask already up to date"
else
    git -C dist/tap commit --quiet -m "zapinator $VERSION"
    git -C dist/tap push --quiet
fi

echo "==> released $VERSION"
echo "    curl -fsSL $BASE_URL | bash"
echo "    brew install --cask kunalbagaria/zapinator/zapinator"
